def _qt_translator(lang_code):
    """Qt's own translator for a menu language, or None if Qt has none."""
    if lang_code not in _QT_LOCALES:
        return None
    if lang_code not in _qt_translators:
        import os
        from PySide6.QtCore import QTranslator, QLibraryInfo
        import PySide6
        translator = QTranslator()
        name = f"qtbase_{_QT_LOCALES[lang_code]}"
        folders = (QLibraryInfo.path(QLibraryInfo.TranslationsPath),
                   os.path.join(os.path.dirname(PySide6.__file__), "translations"))
        _qt_translators[lang_code] = translator if any(translator.load(name, f) for f in folders) else None
    return _qt_translators[lang_code]


def install_qt_translator(lang_code):
    """Let Qt's own dialogs and standard buttons speak the menu language (where Qt has it)."""
    global _installed_translator
    from PySide6.QtCore import QCoreApplication
    app = QCoreApplication.instance()
    if app is None:
        return
    if _installed_translator is not None:
        app.removeTranslator(_installed_translator)
        _installed_translator = None
    translator = _qt_translator(lang_code)
    if translator is not None:
        app.installTranslator(translator)
        _installed_translator = translator


def _bible_reference(reference, lang_code):
    """A reference such as "Acts 4:24-26" with the book name a Bible in that language uses,
    or None if there is no Bible in that language."""
    import bible_loader as bl
    english = MENU_LANGUAGE_ENGLISH.get(lang_code)
    canonical = bl._get_book_names().get("canonical", [])
    book, _, numbers = reference.rpartition(" ")
    for abbr, _, lang in bl.get_available_translations():
        if lang == english and book in canonical:
            native = bl._native_names(abbr) or []
            index = canonical.index(book)
            if index < len(native):
                return f"{native[index]} {numbers}"
    return None


def get_string(key, lang_code):
    """Get a translated string by key for the given language code.
    Falls back to English if the language or key is not found."""
    if (key, lang_code) in _cache:
        return _cache[(key, lang_code)]
    lang_data = LANGUAGES.get(lang_code, LANGUAGES["en"])
    text = lang_data["strings"].get(key, LANGUAGES["en"]["strings"].get(key, key))
    if lang_code != "en" and lang_code in LANGUAGES:
        if key in _QT_BUTTONS:
            translator = _qt_translator(lang_code)
            qt_text = translator.translate("QPlatformTheme", _QT_BUTTONS[key]) if translator else ""
            if qt_text:
                text = qt_text.replace("&", "")
        elif key in _REFERENCES:
            local = _bible_reference(_REFERENCES[key], lang_code)
            if local and key == "Acts 4:24-26":
                text = local
            elif local:
                # The reference in parentheses (also full-width, as in Japanese)
                text = re.sub(r"([(\uff08])[^()\uff08\uff09]*\d+:\d+[^()\uff08\uff09]*([)\uff09])",
                              lambda m: f"{m.group(1)}{local}{m.group(2)}", text, count=1)
    _cache[(key, lang_code)] = text
    return text


def get_translated_language_name(english_name, menu_lang_code):
    """Translate a language name (in English) into the menu language."""
    name_map = _LANGUAGE_NAMES.get(english_name)
    if name_map:
        return name_map.get(menu_lang_code, english_name)
    return english_name


def get_available_languages():
    """Return sorted list of (language_code, native_name) tuples."""
    return sorted(
        ((code, data["name"]) for code, data in LANGUAGES.items()),
        key=lambda x: _sort_key(x[1])
    )


def _sort_key(name):
    """Alphabetical by letter, ignoring accents, so Čeština sorts with C (not after Z)."""
    import unicodedata
    return "".join(c for c in unicodedata.normalize("NFKD", name.casefold()) if not unicodedata.combining(c))